
-- =====================================================
-- PROJECT: Customer Churn & Retention Intelligence
-- PHASE 2: Customer Revenue Segmentation
-- STEP 10: One-Time vs Repeat Customer Revenue
-- PURPOSE:
-- Compare customer count, delivered order count,
-- total product revenue and average revenue per customer.
-- =====================================================


-- STEP 1: Calculate delivered revenue for each customer
WITH customer_revenue AS (

    SELECT
        -- Identify the real customer across multiple orders
        c.customer_unique_id,

        -- Count the customer's distinct delivered orders
        COUNT(DISTINCT o.order_id) AS delivered_orders,

        -- Calculate product revenue for each customer
        SUM(oi.price) AS product_revenue

    FROM olist.customers c

    -- Connect customers with their orders
    INNER JOIN olist.orders o
        ON c.customer_id = o.customer_id

    -- Connect orders with their purchased items
    INNER JOIN olist.order_items oi
        ON o.order_id = oi.order_id

    -- Include delivered orders only
    WHERE o.order_status = 'delivered'

    -- Aggregate data at the real customer level
    GROUP BY c.customer_unique_id
),


-- STEP 2: Classify customers into two segments
customer_segments AS (

    SELECT
        customer_unique_id,
        delivered_orders,
        product_revenue,

        CASE
            -- Customers with exactly one delivered order
            WHEN delivered_orders = 1 THEN 'One-time'

            -- Customers with more than one delivered order
            ELSE 'Repeat'
        END AS customer_segment

    FROM customer_revenue
)


-- STEP 3: Compare revenue across customer segments
SELECT
    customer_segment,

    -- Total number of customers in each segment
    COUNT(*) AS total_customers,

    -- Total delivered orders in each segment
    SUM(delivered_orders) AS total_orders,

    -- Total product revenue generated by each segment
    ROUND(SUM(product_revenue), 2) AS total_revenue,

    -- Average product revenue per customer
    ROUND(AVG(product_revenue), 2) AS avg_revenue_per_customer

FROM customer_segments

-- Group results by customer segment
GROUP BY customer_segment

-- Display the segment with highest revenue first
ORDER BY total_revenue DESC;
