-- PROJECT: Customer Churn & Retention Intelligence
-- PHASE 2: Customer Revenue Analysis
-- STEP 14: Customer Revenue Concentration
-- PURPOSE:
-- Measure the revenue contribution of the top 1%,
-- top 5% and top 10% of delivered customers.
-- =====================================================

-- STEP 1: Calculate delivered revenue per customer
WITH customer_revenue AS (

    SELECT
        c.customer_unique_id,

        -- Calculate delivered product revenue
        SUM(oi.price) AS customer_revenue

    FROM olist.customers c

    INNER JOIN olist.orders o
        ON c.customer_id = o.customer_id

    INNER JOIN olist.order_items oi
        ON o.order_id = oi.order_id

    WHERE o.order_status = 'delivered'

    GROUP BY c.customer_unique_id
),

-- STEP 2: Rank customers from highest to lowest revenue
ranked_customers AS (

    SELECT
        customer_unique_id,
        customer_revenue,

        -- Assign rank based on customer revenue
        ROW_NUMBER() OVER (
            ORDER BY customer_revenue DESC, customer_unique_id
        ) AS revenue_rank,

        -- Count all customers in the analysis
        COUNT(*) OVER () AS total_customers

    FROM customer_revenue
),

-- STEP 3: Calculate revenue contribution of top groups
revenue_concentration AS (

    SELECT
        -- Total customer count
        MAX(total_customers) AS total_customers,

        -- Total revenue generated by all customers
        SUM(customer_revenue) AS total_revenue,

        -- Revenue generated by the top 1% of customers
        SUM(
            CASE
                WHEN revenue_rank <= CEIL(total_customers * 0.01)
                THEN customer_revenue
                ELSE 0
            END
        ) AS top_1_revenue,

        -- Revenue generated by the top 5% of customers
        SUM(
            CASE
                WHEN revenue_rank <= CEIL(total_customers * 0.05)
                THEN customer_revenue
                ELSE 0
            END
        ) AS top_5_revenue,

        -- Revenue generated by the top 10% of customers
        SUM(
            CASE
                WHEN revenue_rank <= CEIL(total_customers * 0.10)
                THEN customer_revenue
                ELSE 0
            END
        ) AS top_10_revenue

    FROM ranked_customers
)

-- STEP 4: Calculate revenue concentration percentages
SELECT
    total_customers,

    ROUND(total_revenue, 2) AS total_revenue,

    ROUND(
        top_1_revenue * 100.0 / total_revenue, 2
    ) AS top_1_revenue_pct,

    ROUND(
        top_5_revenue * 100.0 / total_revenue, 2
    ) AS top_5_revenue_pct,

    ROUND(
        top_10_revenue * 100.0 / total_revenue, 2
    ) AS top_10_revenue_pct

FROM revenue_concentration;