-- STEP 13: Revenue-Based Customer Classification
-- PURPOSE:
-- Classify delivered customers into four revenue
-- segments using percentile-based thresholds.
-- =====================================================

-- STEP 1: Calculate delivered revenue per customer
WITH customer_revenue AS (

    SELECT
        c.customer_unique_id,

        -- Count distinct delivered orders
        COUNT(DISTINCT o.order_id) AS delivered_orders,

        -- Calculate total delivered product revenue
        SUM(oi.price) AS customer_revenue

    FROM olist.customers c

    INNER JOIN olist.orders o
        ON c.customer_id = o.customer_id

    INNER JOIN olist.order_items oi
        ON o.order_id = oi.order_id

    WHERE o.order_status = 'delivered'

    GROUP BY c.customer_unique_id
),

-- STEP 2: Calculate percentile thresholds
revenue_thresholds AS (

    SELECT
        PERCENTILE_CONT(0.25)
            WITHIN GROUP (ORDER BY customer_revenue) AS p25,

        PERCENTILE_CONT(0.50)
            WITHIN GROUP (ORDER BY customer_revenue) AS p50,

        PERCENTILE_CONT(0.90)
            WITHIN GROUP (ORDER BY customer_revenue) AS p90

    FROM customer_revenue
),

-- STEP 3: Assign each customer to a revenue segment
customer_segments AS (

    SELECT
        cr.customer_unique_id,
        cr.delivered_orders,
        cr.customer_revenue,

        CASE
            WHEN cr.customer_revenue >= rt.p90
                THEN 'Top Value'

            WHEN cr.customer_revenue >= rt.p50
                THEN 'High Value'

            WHEN cr.customer_revenue >= rt.p25
                THEN 'Mid Value'

            ELSE 'Low Value'
        END AS revenue_segment

    FROM customer_revenue cr
    CROSS JOIN revenue_thresholds rt
)

-- STEP 4: Summarize the four customer segments
SELECT
    revenue_segment,

    -- Number of customers in each segment
    COUNT(*) AS total_customers,

    -- Total delivered orders
    SUM(delivered_orders) AS total_orders,

    -- Revenue generated by each segment
    ROUND(SUM(customer_revenue), 2) AS total_revenue,

    -- Average revenue per customer
    ROUND(AVG(customer_revenue), 2) AS avg_revenue_per_customer

FROM customer_segments

GROUP BY revenue_segment

-- Display highest-value segment first
ORDER BY
    CASE revenue_segment
        WHEN 'Top Value' THEN 1
        WHEN 'High Value' THEN 2
        WHEN 'Mid Value' THEN 3
        WHEN 'Low Value' THEN 4
    END;
