    -- Total number of delivered customers
    COUNT(*) AS total_customers,

    -- Average revenue per customer
    ROUND(AVG(customer_revenue), 2) AS avg_customer_revenue,

    -- Median revenue per customer
    ROUND(
        PERCENTILE_CONT(0.50)
        WITHIN GROUP (ORDER BY customer_revenue)::NUMERIC,
        2
    ) AS median_customer_revenue,

    -- 25th percentile
    ROUND(
        PERCENTILE_CONT(0.25)
        WITHIN GROUP (ORDER BY customer_revenue)::NUMERIC,
        2
    ) AS revenue_25th_percentile,

    -- 75th percentile
    ROUND(
        PERCENTILE_CONT(0.75)
        WITHIN GROUP (ORDER BY customer_revenue)::NUMERIC,
        2
    ) AS revenue_75th_percentile,

    -- 90th percentile
    ROUND(
        PERCENTILE_CONT(0.90)
        WITHIN GROUP (ORDER BY customer_revenue)::NUMERIC,
        2
    ) AS revenue_90th_percentile,

    -- Maximum revenue generated by one customer
